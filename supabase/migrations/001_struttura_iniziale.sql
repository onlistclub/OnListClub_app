  );
$function$;

-- ── nearby_clubs: ricerca locali entro raggio_km dato (lat/lng utente) ────────
CREATE OR REPLACE FUNCTION public.nearby_clubs(
  user_lat   double precision,
  user_lng   double precision,
  raggio_km  double precision DEFAULT 50
)
RETURNS TABLE(
  id uuid,
  nome text,
  indirizzo text,
  citta text,
  id_citta uuid,
  logo_url text,
  foto_url text,
  famosita integer,
  generi_musicali text[],
  prezzo_indicativo smallint,
  descrizione text,
  link_tripadvisor text,
  lat double precision,
  lng double precision,
  distanza_km double precision
)
LANGUAGE sql
STABLE
AS $function$
  SELECT
    l.id,
    l.nome,
    l.indirizzo,
    c.nome_citta                    AS citta,
    l.id_citta,
    l.logo_url,
    l.foto_url,
    l.famosita,
    l.generi_musicali,
    l.prezzo_indicativo,
    l.descrizione,
    l.link_tripadvisor,
    COALESCE(l.lat, c.lat)          AS lat,
    COALESCE(l.lng, c.lng)          AS lng,
    ROUND(
      ST_Distance(
        ST_MakePoint(COALESCE(l.lng, c.lng), COALESCE(l.lat, c.lat))::geography,
        ST_MakePoint(user_lng, user_lat)::geography
      )::numeric / 1000,
      2
    )::FLOAT                        AS distanza_km
  FROM public.locali l
  LEFT JOIN public.citta c ON c.id_citta = l.id_citta
  WHERE
    COALESCE(l.lat, c.lat) IS NOT NULL
    AND COALESCE(l.lng, c.lng) IS NOT NULL
    AND ST_DWithin(
      ST_MakePoint(COALESCE(l.lng, c.lng), COALESCE(l.lat, c.lat))::geography,
      ST_MakePoint(user_lng, user_lat)::geography,
      raggio_km * 1000
    )
  ORDER BY distanza_km ASC;
$function$;

-- ── register_user_transaction: signup atomico utente + telefono ───────────────
CREATE OR REPLACE FUNCTION public.register_user_transaction(
  p_id_utente   uuid,
  p_nome        text,
  p_cognome     text,
  p_email       text,
  p_data_nascita date,
  p_telefono    text,
  p_country_iso text
)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_is_adult   boolean := false;
  v_country_id uuid    := null;
  v_now        timestamptz := now();
  v_dial       text    := null;
  v_e164       text    := null;
BEGIN
  -- Hardening: solo l'utente loggato può registrare il proprio profilo
  IF auth.uid() IS NULL OR auth.uid() <> p_id_utente THEN
    RAISE EXCEPTION 'Forbidden: caller is not the target user'
      USING ERRCODE = '42501';
  END IF;

  IF p_nome IS NULL OR length(trim(p_nome)) = 0 THEN
    RAISE EXCEPTION 'Nome obbligatorio';
  END IF;
  IF p_cognome IS NULL OR length(trim(p_cognome)) = 0 THEN
    RAISE EXCEPTION 'Cognome obbligatorio';
  END IF;
  IF p_data_nascita IS NULL THEN
    RAISE EXCEPTION 'Data di nascita obbligatoria';
  END IF;
  IF p_telefono IS NULL OR length(trim(p_telefono)) < 7 THEN
    RAISE EXCEPTION 'Telefono non valido';
  END IF;

  v_is_adult := (date_part('year', age(current_date, p_data_nascita)) >= 18);

  SELECT id, numero_prefisso
  INTO v_country_id, v_dial
  FROM public.paesi
  WHERE upper(iso_code) = upper(p_country_iso)
  LIMIT 1;

  v_e164 := replace(coalesce(p_telefono, ''), ' ', '');
  IF v_e164 IS NULL OR v_e164 = '' THEN
    RAISE EXCEPTION 'Telefono non valido';
  END IF;
  IF v_e164 !~ '^\+' THEN
    v_e164 := '+' || v_e164;
  END IF;

  INSERT INTO public.utenti
    (id, nome, cognome, email, data_nascita, maggiorenne, created_at)
  VALUES
    (p_id_utente, p_nome, p_cognome, p_email, p_data_nascita, v_is_adult, v_now)
  ON CONFLICT (id) DO UPDATE
    SET nome         = EXCLUDED.nome,
        cognome      = EXCLUDED.cognome,
        email        = EXCLUDED.email,
        data_nascita = EXCLUDED.data_nascita,
        maggiorenne  = EXCLUDED.maggiorenne,
        updated_at   = v_now;

  INSERT INTO public.utenti_numeri_telefono
    (id_utente, country_id, telefono, is_primary, is_verified, created_at)
  VALUES
    (p_id_utente, v_country_id, v_e164, true, false, v_now)
  ON CONFLICT (id_utente, telefono) DO UPDATE
    SET country_id  = EXCLUDED.country_id,
        is_primary  = EXCLUDED.is_primary,
        is_verified = EXCLUDED.is_verified,
        updated_at  = v_now;

  RETURN json_build_object(
    'user_id',     p_id_utente,
    'country_id',  v_country_id,
    'maggiorenne', v_is_adult,
    'status',      'ok'
  );
END;
$function$;

