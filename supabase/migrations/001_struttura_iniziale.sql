-- ── fn_decrement_prevendita_stock: BEFORE INSERT su prenotazioni_prevendite ──
CREATE OR REPLACE FUNCTION public.fn_decrement_prevendita_stock()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $function$
DECLARE
  v_remaining integer;
BEGIN
  -- Decremento atomico con lock implicito su UPDATE
  UPDATE public.prevendite
  SET quantita_disponibile = quantita_disponibile - 1
  WHERE id_prevendita = NEW.id_prevendita
    AND quantita_disponibile > 0
  RETURNING quantita_disponibile INTO v_remaining;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Prevendita esaurita (id=%)', NEW.id_prevendita
      USING ERRCODE = 'P0001';
  END IF;

  RETURN NEW;
END;
$function$;

-- ── fn_restore_prevendita_stock: AFTER UPDATE su prenotazioni quando annullata ─
CREATE OR REPLACE FUNCTION public.fn_restore_prevendita_stock()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $function$
BEGIN
  -- Specchia il decremento: 1 unità di stock per ogni riga in
  -- prenotazioni_prevendite collegata a questa prenotazione.
  UPDATE public.prevendite pv
  SET quantita_disponibile = pv.quantita_disponibile + sub.cnt
  FROM (
    SELECT id_prevendita, COUNT(*) AS cnt
    FROM public.prenotazioni_prevendite
    WHERE id_prenotazione = NEW.id
    GROUP BY id_prevendita
  ) sub
  WHERE pv.id_prevendita = sub.id_prevendita;

  RETURN NEW;
END;
$function$;

-- ── fn_update_posti_prenotati: AFTER INSERT/UPDATE/DELETE su prenotazioni ─────
CREATE OR REPLACE FUNCTION public.fn_update_posti_prenotati()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $function$
DECLARE
  v_evento_id uuid;
  v_count     integer;
BEGIN
  v_evento_id := COALESCE(NEW.id_evento, OLD.id_evento);

  SELECT COALESCE(SUM(n_persone), 0)
  INTO v_count
  FROM public.prenotazioni
  WHERE id_evento = v_evento_id
    AND stato = 'confermata';

  UPDATE public.eventi
  SET posti_prenotati = v_count,
      updated_at      = now()
  WHERE id = v_evento_id;

  RETURN COALESCE(NEW, OLD);
END;
$function$;

-- ── get_tavoli_disponibilita: rpc usata dall'app per la mappa tavoli ──────────
