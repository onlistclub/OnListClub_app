-- =============================================================================
-- OnList Club — Struttura iniziale del database (replica del progetto di
-- sviluppo `ppbxhedbludoqnagzugm`).
--
-- Eseguire UNA SOLA VOLTA su un progetto Supabase VUOTO per ottenere la
-- stessa struttura senza dati.
--
-- Ordine di esecuzione:
--   1. Estensioni
--   2. Tabelle (in ordine topologico di dipendenza FK)
--   3. Foreign Key
--   4. Indici
--   5. Funzioni
--   6. Trigger
--   7. ENABLE RLS
--   8. Policy RLS
--   9. View
--
-- NOTE IMPORTANTI (vedi anche il messaggio di accompagnamento):
--   • Le tabelle `utenti`, `notifiche`, `analytics_events` referenziano
--     `auth.users` (schema di Supabase Auth). Questo schema esiste già su
--     ogni progetto Supabase, quindi le FK funzionano subito.
--   • Le function usano `auth.uid()` (Supabase Auth) e `SECURITY DEFINER`.
--     Su un progetto fresh saranno di proprietà di `postgres`.
--   • La function `get_gestore_by_codice` referenzia una tabella `clubs`
--     che NON esiste (la tabella è `locali`). È un bug del DB sorgente:
--     la function viene ricreata identica per fedeltà, MA da fixare prima
--     che venga usata in produzione. Vedi nota a fondo file.
-- =============================================================================


-- =============================================================================
-- 1. ESTENSIONI
-- =============================================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto      WITH SCHEMA extensions;  -- gen_random_uuid()
CREATE EXTENSION IF NOT EXISTS "uuid-ossp"   WITH SCHEMA extensions;  -- uuid_generate_v4() (legacy)
CREATE EXTENSION IF NOT EXISTS moddatetime   WITH SCHEMA extensions;  -- trigger updated_at automatico
CREATE EXTENSION IF NOT EXISTS postgis       WITH SCHEMA public;      -- geography per coordinate
CREATE EXTENSION IF NOT EXISTS pg_trgm       WITH SCHEMA public;      -- gin_trgm_ops per ricerca città


-- =============================================================================
-- 2. TABELLE (ordine topologico: le referenziate prima delle referenzianti)
-- =============================================================================

-- ── Anagrafiche geografiche ───────────────────────────────────────────────────

CREATE TABLE public.provincia (
  id_provincia   uuid NOT NULL DEFAULT gen_random_uuid(),
  sigla          varchar NOT NULL,
  nome_provincia text    NOT NULL,
  CONSTRAINT provincia_pkey PRIMARY KEY (id_provincia),
  CONSTRAINT provincia_sigla_key UNIQUE (sigla)
);

CREATE TABLE public.citta (
  id_citta     uuid NOT NULL DEFAULT gen_random_uuid(),
  nome_citta   text NOT NULL,
  id_provincia uuid,
  posizione    geography,
  lat          double precision,
  lng          double precision,
  CONSTRAINT citta_pkey PRIMARY KEY (id_citta)
);

CREATE TABLE public.cap (
  id_cap     uuid NOT NULL DEFAULT gen_random_uuid(),
  cap_valore varchar NOT NULL,
  id_citta   uuid,
  CONSTRAINT cap_pkey PRIMARY KEY (id_cap)
);

CREATE TABLE public.posti_famosi (
  id         uuid NOT NULL DEFAULT gen_random_uuid(),
  nome       varchar NOT NULL,
  id_citta   uuid,
  lat        double precision NOT NULL,
  lng        double precision NOT NULL,
  created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT posti_famosi_pkey PRIMARY KEY (id)
);

-- ── Paesi (prefissi telefonici) ───────────────────────────────────────────────

CREATE TABLE public.paesi (
  id              uuid    NOT NULL DEFAULT gen_random_uuid(),
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamp   NOT NULL DEFAULT now(),
  iso_code        varchar NOT NULL,
  nome            text    NOT NULL,
  numero_prefisso varchar NOT NULL,
  CONSTRAINT countries_phone_pkey PRIMARY KEY (id),
  CONSTRAINT countries_phone_nome_key UNIQUE (nome)
);
COMMENT ON TABLE public.paesi IS
  'Elenco di paesi da dove estrarre il prefisso per il numero di telefono dell''utente';

-- ── Utenti ────────────────────────────────────────────────────────────────────

-- public.utenti.id estende auth.users.id (one-to-one). Su Supabase vuoto
-- auth.users esiste già — quindi la FK non dà errori.
CREATE TABLE public.utenti (
  id            uuid NOT NULL,
  email         text,
  nome          text,
  cognome       text,
  data_nascita  date,
  maggiorenne   boolean,
  created_at    timestamptz DEFAULT now(),
  updated_at    timestamptz DEFAULT now(),
  raggio_km     integer DEFAULT 20,
  CONSTRAINT users_pkey PRIMARY KEY (id),
  CONSTRAINT users_email_key UNIQUE (email)
);

CREATE TABLE public.utenti_numeri_telefono (
  id          bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz,
  id_utente   uuid,
  country_id  uuid,
  telefono    varchar,
  is_primary  boolean,
  is_verified boolean,
  CONSTRAINT user_phones_pkey PRIMARY KEY (id)
);

-- ── Locali e personale ────────────────────────────────────────────────────────

CREATE TABLE public.locali (
  id                 uuid NOT NULL DEFAULT gen_random_uuid(),
  nome               text NOT NULL,
  logo_url           text,
  indirizzo          text,
  telefono           text,
  email              text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  famosita           integer NOT NULL DEFAULT 0,
  generi_musicali    text[]  NOT NULL DEFAULT '{}'::text[],
  foto_url           text,
  prezzo_indicativo  smallint NOT NULL DEFAULT 1,
  link_tripadvisor   text,
  descrizione        text,
  id_citta           uuid,
  posizione          geography,
  lat                double precision,
  lng                double precision,
  CONSTRAINT clubs_pkey PRIMARY KEY (id)
);
COMMENT ON TABLE public.locali IS 'Locali/discoteche registrati sulla piattaforma';

CREATE TABLE public.gestori (
  id         uuid NOT NULL DEFAULT gen_random_uuid(),
  club_id    uuid NOT NULL,
  codice     text NOT NULL,
  nome       text,
  ruolo      text NOT NULL DEFAULT 'admin'::text,
  attivo     boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  email      text,
  CONSTRAINT gestori_pkey PRIMARY KEY (id),
  CONSTRAINT gestori_codice_key UNIQUE (codice)
);
COMMENT ON TABLE public.gestori IS 'Gestori del locale con accesso al gestionale';

CREATE TABLE public.staff (
  id         uuid NOT NULL DEFAULT gen_random_uuid(),
  club_id    uuid NOT NULL,
  nome       text NOT NULL,
  ruolo      text,
  telefono   text,
  email      text,
  stato      text NOT NULL DEFAULT 'green'::text,
  attivo     boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT staff_pkey PRIMARY KEY (id),
  CONSTRAINT staff_stato_check CHECK (stato = ANY (ARRAY['green'::text, 'orange'::text, 'blue'::text]))
);
COMMENT ON TABLE public.staff IS 'Staff del locale (PR, barman, sicurezza, ecc.)';

CREATE TABLE public.ingressi_giornalieri (
  id      uuid NOT NULL DEFAULT gen_random_uuid(),
  club_id uuid NOT NULL,
  data    date NOT NULL,
  count   integer NOT NULL DEFAULT 0,
  CONSTRAINT ingressi_giornalieri_pkey PRIMARY KEY (id),
  CONSTRAINT ingressi_giornalieri_club_id_data_key UNIQUE (club_id, data)
);
COMMENT ON TABLE public.ingressi_giornalieri IS
  'Conteggio ingressi per giorno (per i grafici dashboard)';

-- ── Eventi & prevendite ───────────────────────────────────────────────────────

CREATE TABLE public.eventi (
  id                uuid NOT NULL DEFAULT gen_random_uuid(),
  club_id           uuid NOT NULL,
  nome              text NOT NULL,
  descrizione       text,
  ingressi_previsti integer NOT NULL DEFAULT 0,
  incasso_previsto  numeric NOT NULL DEFAULT 0,
  prezzo_ingresso   numeric,
  locandina_url     text,
  stato             text NOT NULL DEFAULT 'attivo'::text,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  generi_musicali   text[] NOT NULL DEFAULT '{}'::text[],
  posti_prenotati   integer NOT NULL DEFAULT 0,
  inizio_evento     timestamptz,
  fine_evento       timestamptz,
  CONSTRAINT eventi_pkey PRIMARY KEY (id),
  CONSTRAINT eventi_stato_check CHECK (
    stato = ANY (ARRAY['attivo'::text, 'bozza'::text, 'archiviato'::text, 'annullato'::text])
  )
);
COMMENT ON TABLE public.eventi IS 'Serate ed eventi del locale';

CREATE TABLE public.prevendite (
  id_prevendita        uuid NOT NULL DEFAULT gen_random_uuid(),
  id_evento            uuid NOT NULL,
  prezzo               numeric NOT NULL,
  tipo                 varchar,
  descrizione          text,
  validita             varchar,
  quantita_disponibile integer NOT NULL DEFAULT 0,
  CONSTRAINT prevendita_pkey PRIMARY KEY (id_prevendita)
);

-- ── Tavoli ────────────────────────────────────────────────────────────────────

CREATE TABLE public.tavoli (
  id_tavolo          uuid NOT NULL DEFAULT gen_random_uuid(),
  nome_tavolo        varchar NOT NULL,
  numero_tavolo      integer,
  numero_persone_max integer,
  prezzo_minimo      numeric,
  id_locale          uuid,
  capacita           integer NOT NULL DEFAULT 4,
  posizione          text,
  CONSTRAINT tavolo_pkey PRIMARY KEY (id_tavolo)
);

CREATE TABLE public.tavoli_eventi (
  id         uuid NOT NULL DEFAULT gen_random_uuid(),
  id_tavolo  uuid NOT NULL,
  id_evento  uuid NOT NULL,
  stato      text NOT NULL DEFAULT 'disponibile'::text,
  created_at timestamptz DEFAULT now(),
  CONSTRAINT tavoli_eventi_pkey PRIMARY KEY (id),
  CONSTRAINT tavoli_eventi_id_tavolo_id_evento_key UNIQUE (id_tavolo, id_evento)
);

-- ── Drink ─────────────────────────────────────────────────────────────────────

CREATE TABLE public.drink (
  id_drink uuid NOT NULL DEFAULT gen_random_uuid(),
  nome     varchar NOT NULL,
  prezzo   numeric NOT NULL,
  CONSTRAINT drink_pkey PRIMARY KEY (id_drink)
);

-- ── Ordini & prenotazioni ─────────────────────────────────────────────────────

CREATE TABLE public.ordini (
  id                          uuid NOT NULL DEFAULT gen_random_uuid(),
  utente_id                   uuid NOT NULL,
  importo_totale              numeric NOT NULL,
  valuta                      text NOT NULL DEFAULT 'eur'::text,
  stato                       text NOT NULL DEFAULT 'pending'::text,
  stripe_payment_intent_id    text,
  stripe_checkout_session_id  text,
  stripe_customer_id          text,
  stripe_payment_method_id    text,
  stripe_receipt_url          text,
  stripe_refund_id            text,
  note                        text,
  created_at                  timestamptz NOT NULL DEFAULT now(),
  updated_at                  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ordini_pkey PRIMARY KEY (id),
  CONSTRAINT ordini_importo_totale_check CHECK (importo_totale >= 0::numeric),
  CONSTRAINT ordini_stato_check CHECK (
    stato = ANY (ARRAY['pending'::text, 'pagato'::text, 'fallito'::text, 'rimborsato'::text, 'annullato'::text])
  )
);

CREATE TABLE public.prenotazioni (
  id              uuid NOT NULL DEFAULT gen_random_uuid(),
  id_evento       uuid NOT NULL,
  id_utente       uuid,
  nome_cliente    text NOT NULL,
  n_persone       integer NOT NULL DEFAULT 1,
  telefono        text,
  note            text,
  stato           text NOT NULL DEFAULT 'in_attesa'::text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  id_ordine       uuid,
  id_prevendita   uuid,
  prezzo_totale   numeric DEFAULT 0.00,
  CONSTRAINT prenotazioni_pkey PRIMARY KEY (id)
);

CREATE TABLE public.prenotazioni_tavolo (
  id              uuid NOT NULL DEFAULT gen_random_uuid(),
  id_tavolo       uuid NOT NULL,
  id_evento       uuid,
  n_persone       integer,
  nome_cliente    text,
  stato           text,
  id_utente       uuid,
  id_drink        uuid,
  quantita_drink  integer DEFAULT 0,
  id_prenotazione uuid,
  quantita        integer DEFAULT 1,
  CONSTRAINT prenotazioni_tavolo_pkey PRIMARY KEY (id)
);

CREATE TABLE public.prenotazioni_prevendite (
  id              uuid NOT NULL DEFAULT gen_random_uuid(),
  id_prevendita   uuid NOT NULL,
  id_prenotazione uuid NOT NULL,
  id_utente       uuid,
  nome            text NOT NULL,
  cognome         text NOT NULL,
  data_nascita    date NOT NULL,
  CONSTRAINT prenotazioni_prevendite_pkey PRIMARY KEY (id)
);

-- ── Preferiti, notifiche, analytics ───────────────────────────────────────────

CREATE TABLE public.preferiti (
  id         uuid NOT NULL DEFAULT gen_random_uuid(),
  id_utente  uuid NOT NULL,
  locale_id  uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT preferiti_pkey PRIMARY KEY (id),
  CONSTRAINT preferiti_user_id_locale_id_key UNIQUE (id_utente, locale_id)
);

CREATE TABLE public.notifiche (
  id         uuid NOT NULL DEFAULT gen_random_uuid(),
  utente_id  uuid NOT NULL,
  titolo     text NOT NULL,
  messaggio  text NOT NULL,
  tipo       text NOT NULL,
  related_id uuid,
  letto      boolean DEFAULT false,
  created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT notifiche_pkey PRIMARY KEY (id)
);

CREATE TABLE public.analytics_events (
  id          uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at  timestamptz DEFAULT now(),
  user_id     uuid,
  event_name  text NOT NULL,
  metadata    jsonb DEFAULT '{}'::jsonb,
  platform    text,
  app_version text,
  is_debug    boolean DEFAULT false,
  CONSTRAINT analytics_events_pkey PRIMARY KEY (id)
);


